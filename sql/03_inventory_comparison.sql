-- 03_inventory_comparison.sql
-- Compare end-of-day inventory between 30 September and 31 October 2026.
-- DATE literals avoid dependence on the session NLS_DATE_FORMAT.

WITH A AS (
    SELECT
        MD.TRAN_DATE,
        MD.STORE,
        MD.ITEM,
        SUM(MD.STOCK_ON_HAND + MD.IN_TRANSIT_QTY) AS EOH_QTY_30SEP2026
    FROM MPP_DETAIL_SOH MD
    WHERE MD.TRAN_DATE >= DATE '2026-09-30'
      AND MD.TRAN_DATE <  DATE '2026-10-01'
      AND MD.STORE IN (101, 102, 103)
      AND EXISTS (
          SELECT 1
          FROM ITEM_MASTER IM
          JOIN DEPS D
            ON D.DEPT = IM.DEPT
          WHERE D.PURCHASE_TYPE = 0
            AND IM.ITEM = MD.ITEM
      )
      AND MD.ITEM IN (900001)
    GROUP BY MD.TRAN_DATE, MD.STORE, MD.ITEM
),
B AS (
    SELECT
        MD.TRAN_DATE,
        MD.STORE,
        MD.ITEM,
        SUM(MD.STOCK_ON_HAND + MD.IN_TRANSIT_QTY) AS EOH_QTY_31OCT2026
    FROM MPP_DETAIL_SOH MD
    WHERE MD.TRAN_DATE >= DATE '2026-10-31'
      AND MD.TRAN_DATE <  DATE '2026-11-01'
      AND MD.STORE IN (101, 102, 103)
      AND EXISTS (
          SELECT 1
          FROM ITEM_MASTER IM
          JOIN DEPS D
            ON D.DEPT = IM.DEPT
          WHERE D.PURCHASE_TYPE = 0
            AND IM.ITEM = MD.ITEM
      )
      AND MD.ITEM IN (900001)
    GROUP BY MD.TRAN_DATE, MD.STORE, MD.ITEM
)
SELECT
    A.ITEM,
    A.STORE,
    A.EOH_QTY_30SEP2026,
    NVL(B.EOH_QTY_31OCT2026, 0) AS EOH_QTY_31OCT2026,
    NVL(B.EOH_QTY_31OCT2026, 0) - A.EOH_QTY_30SEP2026 AS STOCK_DIFFERENCE,
    CASE
        WHEN B.ITEM IS NULL THEN 'NO OCTOBER DATA'
        WHEN NVL(B.EOH_QTY_31OCT2026, 0) > A.EOH_QTY_30SEP2026 THEN 'INCREASE'
        WHEN NVL(B.EOH_QTY_31OCT2026, 0) < A.EOH_QTY_30SEP2026 THEN 'DECREASE'
        ELSE 'NO CHANGE'
    END AS STATUS
FROM A
LEFT JOIN B
    ON B.ITEM = A.ITEM
   AND B.STORE = A.STORE
ORDER BY A.ITEM, A.STORE;
